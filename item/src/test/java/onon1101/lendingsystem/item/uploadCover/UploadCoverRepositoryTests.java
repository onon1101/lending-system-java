package onon1101.lendingsystem.item.uploadCover;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.r2dbc.spi.ConnectionFactories;
import java.time.Instant;
import java.util.UUID;
import onon1101.lendingsystem.item.uploadCover.repository.R2dbcUploadCoverReader;
import onon1101.lendingsystem.item.uploadCover.repository.R2dbcUploadCoverWriter;
import org.junit.jupiter.api.Test;
import org.springframework.r2dbc.core.DatabaseClient;

class UploadCoverRepositoryTests {
    @Test
    void enforcesOwnershipAndConditionalReplacementIncludingNullKey() throws Exception {
        var db =
                DatabaseClient.create(
                        new io.r2dbc.pool.ConnectionPool(
                                io.r2dbc.pool.ConnectionPoolConfiguration.builder(
                                                ConnectionFactories.get(
                                                        "r2dbc:h2:mem:///image_"
                                                                + UUID.randomUUID()
                                                                        .toString()
                                                                        .replace("-", "")
                                                                + "?options=DB_CLOSE_DELAY=-1"))
                                        .initialSize(1)
                                        .maxSize(1)
                                        .build()));
        db.sql(
                        """
                CREATE TABLE items (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    public_id UUID UNIQUE NOT NULL, owner_id BIGINT NOT NULL,
                    status VARCHAR(20) NOT NULL,
                    name VARCHAR(100) NOT NULL DEFAULT 'Item',
                    description VARCHAR(2000) NOT NULL DEFAULT '',
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
                )
                """)
                .fetch()
                .rowsUpdated()
                .block();
        // Validate the production media schema rather than a separate test definition.
        var schema =
                java.nio.file.Files.readString(
                        java.nio.file.Path.of("../app/src/main/resources/schema.sql"));
        var mediaSchema =
                "CREATE TABLE IF NOT EXISTS item_media"
                        + schema.split("CREATE TABLE IF NOT EXISTS item_media", 2)[1];
        for (String statement : mediaSchema.split(";")) {
            if (!statement.isBlank()) {
                db.sql(statement).fetch().rowsUpdated().block();
            }
        }
        db.sql(
                        """
                CREATE TABLE users (
                    id BIGINT PRIMARY KEY, public_id UUID NOT NULL,
                    username VARCHAR(100) NOT NULL, status VARCHAR(20) NOT NULL
                )
                """)
                .fetch()
                .rowsUpdated()
                .block();
        db.sql("INSERT INTO users VALUES (7, :id, 'owner', 'active')")
                .bind("id", UUID.randomUUID())
                .fetch()
                .rowsUpdated()
                .block();
        UUID id = UUID.randomUUID();
        db.sql(
                        "INSERT INTO items (public_id, owner_id, status, updated_at) VALUES (:id, 7, 'available', CURRENT_TIMESTAMP)")
                .bind("id", id)
                .fetch()
                .rowsUpdated()
                .block();
        var reader = new R2dbcUploadCoverReader(db);
        var writer = new R2dbcUploadCoverWriter(db);
        assertNull(reader.findOwnedItem(id, 8).block());
        assertNotNull(reader.findOwnedItem(id, 7).block());
        // Additional media must not become the cover or be affected by cover replacement.
        db.sql(
                        """
                INSERT INTO item_media
                    (public_id, item_id, media_type, object_key, sort_order, created_at, updated_at)
                SELECT :mediaId, id, 'image', 'gallery', 1, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
                FROM items WHERE public_id = :id
                """)
                .bind("mediaId", UUID.randomUUID())
                .bind("id", id)
                .fetch()
                .rowsUpdated()
                .block();
        db.sql(
                        """
                INSERT INTO item_media
                    (public_id, item_id, media_type, object_key, sort_order, created_at, updated_at)
                SELECT :mediaId, id, 'video', 'video', 2, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
                FROM items WHERE public_id = :id
                """)
                .bind("mediaId", UUID.randomUUID())
                .bind("id", id)
                .fetch()
                .rowsUpdated()
                .block();
        assertNull(reader.findOwnedItem(id, 7).block().objectKey());
        var detailReader = new onon1101.lendingsystem.item.retrieve.R2dbcRetrieveItemReader(db);
        var listReader = new onon1101.lendingsystem.item.list.R2dbcListItemsReader(db);
        var pagination = new onon1101.lendingsystem.web.pagination.PaginationRequest(0, 1);
        assertNull(detailReader.findVisibleItem(id, 8).block().coverObjectKey());
        var withoutCover = listReader.findVisibleItems(8, pagination).collectList().block();
        assertEquals(1, withoutCover.size());
        assertNull(withoutCover.getFirst().coverObjectKey());
        org.junit.jupiter.api.Assertions.assertThrows(
                RuntimeException.class,
                () ->
                        db.sql(
                                        """
                        INSERT INTO item_media
                            (public_id, item_id, media_type, object_key, sort_order, created_at, updated_at)
                        SELECT :mediaId, id, 'video', 'invalid-cover', 0, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
                        FROM items WHERE public_id = :id
                        """)
                                .bind("mediaId", UUID.randomUUID())
                                .bind("id", id)
                                .fetch()
                                .rowsUpdated()
                                .block());
        var now = Instant.now();
        assertFalse(writer.replace(id, 8, null, "wrong-owner", now).block());
        assertTrue(writer.replace(id, 7, null, "first", now).block());
        assertFalse(writer.replace(id, 7, null, "stale", now).block());
        assertEquals("first", reader.findOwnedItem(id, 7).block().objectKey());
        assertTrue(writer.replace(id, 7, "first", "second", now).block());
        assertEquals("second", detailReader.findVisibleItem(id, 8).block().coverObjectKey());
        var listed = listReader.findVisibleItems(8, pagination).collectList().block();
        assertEquals(1, listed.size());
        assertEquals("second", listed.getFirst().coverObjectKey());
        assertEquals(
                3L,
                db.sql("SELECT COUNT(*) AS count FROM item_media")
                        .map((row, metadata) -> row.get("count", Long.class))
                        .one()
                        .block());
        assertEquals(
                2L,
                db.sql(
                                "SELECT COUNT(*) AS count FROM item_media WHERE object_key IN ('gallery', 'video')")
                        .map((row, metadata) -> row.get("count", Long.class))
                        .one()
                        .block());
        org.junit.jupiter.api.Assertions.assertThrows(
                RuntimeException.class,
                () ->
                        db.sql(
                                        """
                        INSERT INTO item_media
                            (public_id, item_id, media_type, object_key, sort_order, created_at, updated_at)
                        SELECT :mediaId, id, 'image', 'duplicate-cover', 0, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
                        FROM items WHERE public_id = :id
                        """)
                                .bind("mediaId", UUID.randomUUID())
                                .bind("id", id)
                                .fetch()
                                .rowsUpdated()
                                .block());
        db.sql("UPDATE items SET status = 'archived'").fetch().rowsUpdated().block();
        assertNull(reader.findOwnedItem(id, 7).block());
        assertFalse(writer.replace(id, 7, "second", "third", now).block());
    }
}
