-- Run once against an existing PostgreSQL database before deploying the new backend.
-- The transaction copies all old images before removing the old column.
BEGIN;
LOCK TABLE items IN ACCESS EXCLUSIVE MODE;
CREATE TABLE IF NOT EXISTS item_media
(
    id BIGINT GENERATED By DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,

    item_id BIGINT NOT NULL,
    media_type VARCHAR(10) NOT NULL,
    object_key VARCHAR(512) NOT NULL,
    content_type VARCHAR(100),

    sort_order INTEGER NOT NULL DEFAULT 0,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_item_media_public_id UNIQUE (public_id),
    CONSTRAINT uq_item_media_object_key UNIQUE (object_key),

    CONSTRAINT fk_item_media_item
        FOREIGN KEY (item_id)
        REFERENCES items(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_item_media_type
        CHECK(media_type = 'image' OR media_type = 'video'),

    CONSTRAINT ck_item_media_object_key_not_blank
        CHECK(CHAR_LENGTH(TRIM(object_key)) > 0),

    CONSTRAINT ck_item_media_sort_order
        CHECK(sort_order >= 0),

    CONSTRAINT ck_item_media_cover_image
        CHECK(sort_order <> 0 OR media_type = 'image'),

    CONSTRAINT ck_item_media_updated_at
        CHECK(updated_at >= created_at)
);

CREATE INDEX IF NOT EXISTS idx_item_media_item_sort
    ON item_media(item_id, sort_order, id);

-- Each position belongs to one media file. Position zero is the image cover.
CREATE UNIQUE INDEX IF NOT EXISTS uq_item_media_item_sort_order
    ON item_media(item_id, sort_order);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'items' AND column_name = 'image_object_key'
    ) THEN
        INSERT INTO item_media
            (public_id, item_id, media_type, object_key, sort_order, created_at, updated_at)
        SELECT public_id, id, 'image', image_object_key, 0, created_at, updated_at
        FROM items
        WHERE image_object_key IS NOT NULL;

        ALTER TABLE items DROP COLUMN image_object_key;
    END IF;
END $$;
COMMIT;
