-- 存放使用者資訊
CREATE TABLE IF NOT EXISTS users
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,

    username VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active',

    email VARCHAR(255) NOT NULL,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE, -- 驗證可否發送 mail

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_users_username UNIQUE (username),

    CONSTRAINT uq_users_public_id UNIQUE (public_id),

    CONSTRAINT uq_users_email UNIQUE (email),

    CONSTRAINT ck_users_email_normalized
        CHECK(
            email = LOWER(TRIM(email))
            AND email <> ''
        ),

    CONSTRAINT ck_users_username_lowercase
        CHECK (username = LOWER(username)),

    CONSTRAINT ck_users_status
        CHECK (status IN ('active', 'suspended', 'deleted'))
);

-- 冪等請求紀錄必須在 users 之後建立，因為 actor_id 參照 users.public_id。
CREATE TABLE IF NOT EXISTS idempotency_records
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id UUID NOT NULL,
    operation VARCHAR(100) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'processing',
    response_body JSONB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITH TIME ZONE,
    expires_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_idempotency_records_actor
        FOREIGN KEY (actor_id) REFERENCES users(public_id) ON DELETE CASCADE,
    CONSTRAINT uq_idempotency_request
        UNIQUE (actor_id, operation, idempotency_key),
    CONSTRAINT ck_idempotency_status
        CHECK (status IN ('processing', 'completed')),
    CONSTRAINT ck_idempotency_completed
        CHECK ((status = 'processing' AND completed_at IS NULL)
            OR (status = 'completed' AND completed_at IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS idx_idempotency_records_created_at
    ON idempotency_records(created_at);

-- 存放使用者授權認證表
CREATE TABLE IF NOT EXISTS user_auth_identities
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL,

    provider VARCHAR(30) NOT NULL,
    provider_subject VARCHAR(255) NOT NULL,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_user_auth_identities_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_user_auth_identites_provider_subject
        UNIQUE (provider, provider_subject),

    CONSTRAINT uq_user_auth_identites_user_provider
        UNIQUE (user_id, provider),

    CONSTRAINT ck_user_auth_identities_provider
        CHECK (provider IN ('password', 'google', 'apple', 'github'))
);

CREATE INDEX IF NOT EXISTS idx_user_auth_identities_user_id
    ON user_auth_identities(user_id);


-- 存放密碼
CREATE TABLE IF NOT EXISTS user_password_credentials
(
    auth_identity_id BIGINT PRIMARY KEY,

    password_hash VARCHAR(255) NOT NULL,

    password_changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    failed_attempts INTEGER NOT NULL DEFAULT 0,

    locked_until TIMESTAMP WITH TIME ZONE,

    CONSTRAINT fk_user_password_credentials_identity
        FOREIGN KEY (auth_identity_id)
        REFERENCES user_auth_identities(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_user_password_credentials_failed_attempts
        CHECK (failed_attempts >= 0)
);

-- 物品表
CREATE TABLE IF NOT EXISTS items
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    public_id UUID NOT NULL,
    owner_id BIGINT NOT NULL,

    name VARCHAR(100) NOT NULL,
    description VARCHAR(2000) NOT NULL DEFAULT '',

    status VARCHAR(20) NOT NULL DEFAULT 'available',

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                             CONSTRAINT fk_items_owner
                             FOREIGN KEY (owner_id)
    REFERENCES users(id)
                         ON DELETE RESTRICT,

    CONSTRAINT ck_items_name_not_blank
    CHECK (CHAR_LENGTH(TRIM(name)) > 0),

    CONSTRAINT ck_items_status
    CHECK (status IN (
           'available',
           'unavailable',
           'archived'
                     )),

    CONSTRAINT ck_items_updated_at
    CHECK (updated_at >= created_at)
    );

CREATE UNIQUE INDEX IF NOT EXISTS uq_items_public_id
    ON items(public_id);

CREATE INDEX IF NOT EXISTS idx_items_owner_id_status
    ON items(owner_id, status);

CREATE TABLE IF NOT EXISTS item_media
(
    id BIGINT GENERATED By DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,

    item_id BIGINT NOT NULL,
    media_type VARCHAR(10) NOT NULL,
    object_key VARCHAR(512) NOT NULL,
    content_type VARCHAR(100),

    sort_order INTEGER NOT NULL DEFAULT 0,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_item_media_public_id UNIQUE (public_id),
    CONSTRAINT uq_item_media_object_key UNIQUE (object_key),

    CONSTRAINT fk_item_media_item
        FOREIGN KEY (item_id)
        REFERENCES items(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_item_media_type
        CHECK(media_type = 'image' OR media_type = 'video'),

    CONSTRAINT ck_item_media_object_key_not_blank
        CHECK(CHAR_LENGTH(TRIM(object_key)) > 0),

    CONSTRAINT ck_item_media_sort_order
        CHECK(sort_order >= 0),

    CONSTRAINT ck_item_media_cover_image
        CHECK(sort_order <> 0 OR media_type = 'image'),

    CONSTRAINT ck_item_media_updated_at
        CHECK(updated_at >= created_at)
);

CREATE INDEX IF NOT EXISTS idx_item_media_item_sort
    ON item_media(item_id, sort_order, id);

-- Each position belongs to one media file. Position zero is the image cover.
CREATE UNIQUE INDEX IF NOT EXISTS uq_item_media_item_sort_order
    ON item_media(item_id, sort_order);

CREATE TABLE IF NOT EXISTS loan_records
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,

    item_id BIGINT NOT NULL,
    borrower_id BIGINT NOT NULL,
    lender_id BIGINT NOT NULL,
    item_name_snapshot VARCHAR(100) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'pending',
    request_note VARCHAR(2000) NOT NULL DEFAULT '',

    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at TIMESTAMPTZ,
    borrowed_at TIMESTAMPTZ,
    due_at TIMESTAMPTZ,
    returned_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,

    planned_borrow_date DATE,
    plaaned_return_date DATE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT uq_loan_records_public_id UNIQUE (public_id),

    CONSTRAINT fk_loan_records_item
    FOREIGN KEY (item_id)
    REFERENCES items(id) ON DELETE RESTRICT,

    CONSTRAINT fk_loan_records_borrower
    FOREIGN KEY (borrower_id)
    REFERENCES users(id) ON DELETE RESTRICT,

    CONSTRAINT fk_loan_records_lender
    FOREIGN KEY (lender_id)
    REFERENCES users(id) ON DELETE RESTRICT,

    CONSTRAINT ck_loan_records_planned_dates
    CHECK (
        (planned_borrow_date IS NULL AND planned_return_date IS NULL)
    OR
    (
        planned_borrow_date IS NOT NULL
        AND planned_return_date IS NOT NULL
        AND planned_return_date > planned_borrow_date
    )),

    CONSTRAINT ck_loan_records_participants
    CHECK (borrower_id <> lender_id),

    CONSTRAINT ck_loan_records_item_name
    CHECK (CHAR_LENGTH(TRIM(item_name_snapshot)) > 0),

    CONSTRAINT ck_loan_records_status
    CHECK (status IN (
        'pending', 'approved', 'borrowed',
    'returned', 'rejected', 'cancelled')),

    CONSTRAINT ck_loan_records_state_fields
    CHECK (
        (status = 'pending'
         AND approved_at IS NULL AND due_at IS NULL
         AND borrowed_at IS NULL AND returned_at IS NULL)
            OR
        (status = 'approved'
         AND approved_at IS NOT NULL AND due_at IS NOT NULL
         AND borrowed_at IS NULL AND returned_at IS NULL)
            OR
        (status = 'borrowed'
         AND approved_at IS NOT NULL AND due_at IS NOT NULL
         AND borrowed_at IS NOT NULL AND returned_at IS NULL)
            OR
        (status = 'returned'
         AND approved_at IS NOT NULL AND due_at IS NOT NULL
         AND borrowed_at IS NOT NULL AND returned_at IS NOT NULL)
            OR
        (status = 'rejected'
         AND approved_at IS NULL AND due_at IS NULL
         AND borrowed_at IS NULL AND returned_at IS NULL)
            OR
        (status = 'cancelled'
         AND borrowed_at IS NULL AND returned_at IS NULL
         AND (
        (approved_at IS NULL AND due_at IS NULL)
            OR
        (approved_at IS NOT NULL AND due_at IS NOT NULL)
            ))
            ),

    CONSTRAINT ck_loan_records_closed
    CHECK (
    (status IN ('returned', 'rejected', 'cancelled')
    AND closed_at IS NOT NULL)
    OR
(status IN ('pending', 'approved', 'borrowed')
    AND closed_at IS NULL)
    ),

    CONSTRAINT ck_loan_records_time_order
    CHECK (
(approved_at IS NULL OR approved_at >= requested_at)
    AND (due_at IS NULL OR due_at > approved_at)
    AND (borrowed_at IS NULL OR borrowed_at >= approved_at)
    AND (borrowed_at IS NULL OR due_at > borrowed_at)
    AND (returned_at IS NULL OR returned_at >= borrowed_at)
    AND (closed_at IS NULL OR closed_at >= requested_at)
    AND (approved_at IS NULL OR closed_at IS NULL
         OR closed_at >= approved_at)
    AND (returned_at IS NULL OR closed_at = returned_at)
    AND updated_at >= created_at
    ),

    CONSTRAINT ck_loan_records_version CHECK (version >= 0)
);

-- 同一件物品，同時只能有一筆已核准或借出中的紀錄。
CREATE UNIQUE INDEX IF NOT EXISTS uq_loan_records_active_item
    ON loan_records(item_id)
    WHERE status IN ('approved', 'borrowed');

-- 同一人不能對同一件物品重複提出未結束的申請。
CREATE UNIQUE INDEX IF NOT EXISTS uq_loan_records_open_request
    ON loan_records(item_id, borrower_id)
    WHERE status IN ('pending', 'approved', 'borrowed');

CREATE INDEX IF NOT EXISTS idx_loan_records_borrower_history
    ON loan_records(borrower_id, requested_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_loan_records_lender_history
    ON loan_records(lender_id, requested_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_loan_records_item_history
    ON loan_records(item_id, requested_at DESC, id DESC);

CREATE INDEX IF NOT EXISTS idx_loan_records_borrowed_due
    ON loan_records(due_at)
    WHERE status = 'borrowed';
